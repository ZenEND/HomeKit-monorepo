export function localizePhase(phase: RoadmapPhase, language: Language): LocalizedText {
  if (language === 'ua' && ua[phase.id]) return ua[phase.id];
  return { title: phase.title, description: phase.description };
}

export function localizeStep(step: RoadmapStep, language: Language): LocalizedText {
  if (language === 'ua' && ua[step.id]) return ua[step.id];
  return { title: step.title, description: step.description };
}
